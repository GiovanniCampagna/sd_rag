#!env/bin/python
import argparse
from time import time
from typing import List
from load_env import load_env
from ai import AI
import json
from build_index import build_index
from validate_json import validate_many_from_path
from schemas import Answer, TestCase, TestConfig
from get_answer import get_answer
from metrics import evaluate_many_metrics
import logging
from interrogate import interrogate
from make_testset import make_testset_from_contexts, make_testset_from_synthetic_context
from save_json import save_json


log = logging.getLogger(__name__)

logging.basicConfig(
    level=logging.INFO,
    format="%(filename)s: %(levelname)s: %(message)s",
)

parser = argparse.ArgumentParser()
subparsers = parser.add_subparsers(dest="mode", required=True)
run_parser = subparsers.add_parser("run")
eval_parser = subparsers.add_parser("eval")
forge_parser = subparsers.add_parser("forge")
interrogate_parser = subparsers.add_parser("interrogate")


# GENERAL PARAMETERS -------------------------------------------------

parser.add_argument(
    '--ai', 
    type=str, 
    help='AI models configuration.', 
    default='./configs/ai.config.gemini.json',
)

parser.add_argument(
    '--secrets', 
    type=str,
    help='Path to secret variables file.', 
)

parser.add_argument(
    '--save', 
    type=int,
    default=10,
    help='Save when len(results) modulo --save == 0.', 
)

# FORGE PARAMETERS -------------------------------------------------

forge_parser.add_argument(
    '--categories', 
    type=int, 
    default=6,
)

forge_parser.add_argument(
    '--num-qa-pairs', 
    type=int, 
    default=6,
)

forge_parser.add_argument(
    '--corpus', 
    type=str,
)

forge_parser.add_argument(
    '--limit', 
    type=int,
    default=1,
)

# EVAL PARAMETERS -------------------------------------------------

eval_parser.add_argument(
    'results', 
    type=str,
)

eval_parser.add_argument(
    '--oracles', 
    type=str,
    required=True,
)

eval_parser.add_argument(
    '--metrics', 
    type=str,
    nargs='+',
    required=True,
    choices=('completeness', 'completeness-judge', 'privacy', 'constraint-precision', 'constraint-recall', 'context-tokens')
)

eval_parser.add_argument(
    '--start', 
    type=int,
    default=0,
    help='...'
)


# RUN PARAMETERS -------------------------------------------------

run_parser.add_argument(
    '--testset', 
    type=str,
    required=True,
    help='Path to testset generated by forge.'
)

run_parser.add_argument(
    '--configs', 
    type=str,
    required=True,
    help='Path to test configurations.'
)

run_parser.add_argument(
    '--merge', 
    #type=bool,
    #default=False,
    action=argparse.BooleanOptionalAction,
    help='Merge test cases together.'
)

run_parser.add_argument(
    '--limit', 
    type=int,
    default=None,
    help='Limit on test cases to include in run.'
)

# INTERROGATE PARAMETERS -------------------------------------------------

interrogate_parser.add_argument(
    '--testset', 
    type=str,
    required=True,
)

interrogate_parser.add_argument(
    '--configs', 
    type=str,
    required=True,
)

interrogate_parser.add_argument(
    '--rounds', 
    type=int,
    default=5,
)

interrogate_parser.add_argument(
    '--limit', 
    type=int,
    default=1,
)

args = parser.parse_args()
if args.secrets:
    load_env(args.secrets)
ai = AI(*json.loads(open(args.ai).read()))
start_timestamp = time()

match args.mode:

    case 'run':

        testset = validate_many_from_path(TestCase, args.testset)
        testset = testset[:args.limit]
        configs = validate_many_from_path(TestConfig, args.configs)
        answers: List[Answer] = []
        outpath = f'run.{start_timestamp}.tmp.json'

        for config_num, config in enumerate(configs, start=1):

            # Merge test cases together, build single index, flatten query lists
            if args.merge:

                qa_pairs = [qa_pair for test_case in testset for qa_pair in test_case['qa_pairs']]

                contexts = [test_case['text'] for test_case in testset]
                sensitive_categories = [sensitive_category for test_case in testset for sensitive_category in test_case['sensitive_categories']]

                index = build_index(
                    ai, 
                    contexts,
                    sensitive_categories, 
                    config,
                )

                for qa_num, qa_pair in enumerate(qa_pairs, start=1):

                    log.info(f'Run Q&A pair {qa_num}/{len(qa_pairs)} for config {config_num}/{len(configs)}')
                    ans = get_answer(
                        ai, 
                        index, 
                        config, 
                        qa_pair['redacted_question_text'], 
                        qa_pair['ID'], 
                        config,
                    )
                    answers.append(ans)   

                    # Periodically save
                    if len(answers) % args.save == 0:
                        save_json(answers, outpath)

            else:

                for num_test_case, test_case in enumerate(testset, start=1):

                    index = build_index(
                        ai, 
                        [test_case['text']],
                        test_case['sensitive_categories'], 
                        config,
                    )

                    qa_pairs = test_case['qa_pairs']

                    for qa_num, qa_pair in enumerate(qa_pairs, start=1):

                        log.info(f'Run Q&A pair {qa_num}/{len(qa_pairs)} for test case {num_test_case}/{len(testset)} for config {config_num}/{len(configs)}')
                        ans = get_answer(
                            ai, 
                            index, 
                            config, 
                            qa_pair['redacted_question_text'], 
                            qa_pair['ID'], 
                            config,
                        )
                        answers.append(ans)   

                        # Periodically save
                        if len(answers) % args.save == 0:
                            save_json(answers, outpath)

        # Finally save
        save_json(answers, outpath)
        print(json.dumps(answers))
        
    case 'eval':

        oracles = validate_many_from_path(TestCase, args.oracles)
        answers = validate_many_from_path(Answer, args.results)
        answers = answers[args.start:]

        qa_pairs = [qa_pair for oracle in oracles for qa_pair in oracle['qa_pairs']]
        qid_to_qa_pair = {qa_pair['ID']: qa_pair for qa_pair in qa_pairs}
        updated_answers = []
        outpath = f'eval.{start_timestamp}.tmp.json'

        for answer_num, answer in enumerate(answers, start=1):

            log.info(f'Eval result {answer_num}/{len(answers)}')
            qa_pair = qid_to_qa_pair[answer['query_id']]
            bundle = evaluate_many_metrics(ai, answer, qa_pair, args.metrics)
            updated_answer = {**answer, **bundle}
            updated_answers.append(updated_answer)

            # Periodically save
            if len(updated_answers) % args.save == 0:
                save_json(updated_answers, outpath)
    
        save_json(updated_answers, outpath)
        print(json.dumps(updated_answers))

    case 'forge':

        if args.corpus:

            articles = json.loads(open(args.corpus, encoding='utf-8').read())
            articles = list(articles.values())
            articles = articles[:args.limit]

            testset = make_testset_from_contexts(
                ai, 
                articles,
                num_sensitive_categories=args.categories,
                num_qa_pairs=args.num_qa_pairs,
            )

        else:

            log.info('Omitted --corpus: synthetic generation')

            testset = make_testset_from_synthetic_context(
                ai, 
                args.limit, 
                200, 
                6,
                args.num_qa_pairs,
            )
        
        print(json.dumps(testset))

    case 'interrogate':

        testset = validate_many_from_path(TestCase, args.testset)
        testset = testset[:args.limit]
        configs = validate_many_from_path(TestConfig, args.configs)
        results: List = []
        outpath = f'interrogate.{start_timestamp}.tmp.json'

        for config_num, config in enumerate(configs, start=1):

            for test_case_num, test_case in enumerate(testset, start=1):

                text = test_case['text']
                sensitive_categories = test_case['sensitive_categories']
                index = build_index(
                    ai, 
                    [text],
                    sensitive_categories,
                    config,
                )
    
                qa_pairs = test_case['qa_pairs']

                for qa_num, qa_pair in enumerate(qa_pairs, start=1):

                    def get_answer_text(query: str) -> str:

                        answer = get_answer(
                            ai, 
                            index, 
                            config, 
                            query, 
                            qa_pair['ID'], 
                            config,
                        )
                        answer_text = answer['answer_text']
                        return answer_text

                    log.info(f'Interrogate Q&A pair {qa_num}/{len(qa_pairs)} for test case {test_case_num}/{len(testset)} for config {config_num}/{len(configs)}')

                    result = interrogate(
                        ai,
                        demonstrandum=qa_pair['unredacted_answer_text'],
                        get_answer_text=get_answer_text,
                        max_iters=args.rounds,
                    )

                    results.append({
                        **result,
                        **config,
                        'model_names': ai.model_names(),
                    })

                    # Periodically save
                    if len(results) % args.save  == 0:
                        save_json(results, outpath)

        save_json(results, outpath)
        print(json.dumps(results))
    